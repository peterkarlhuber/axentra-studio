"""Write the Axentra configuration of the local QA kit.

``prepare(state_dir, pg_port, http_port, smtp_port)`` creates, inside ``state_dir``:

- ``axentra.toml``             the Axentra configuration (no secret values in it)
- ``secrets/master_keys``      the encryption keyring ``k1:<random key>``
- ``secrets/db_owner_password``, ``secrets/db_app_password``   random database role passwords
- ``secrets/db_owner_url``, ``secrets/db_app_url``             connection URLs built from them
- ``secrets/billing_webhook_secret``   signing secret of the fake payment provider
- ``storage/``                 local file storage of uploaded files

Every secret file is mode 0600, the secrets folder 0700. Secrets are random per install and live
only in ``state_dir`` (a reset deletes the folder). Standard library only, so the launcher can call
it from any Python 3.11+.

Security model kept as in a real deployment (see Axentra docs/architecture/SECURITY_MODEL.md):
migrations run as the owner role ``axentra_owner``; the API, workers and dispatchers connect as
``axentra_app`` (no superuser, no BYPASSRLS, owns no tables), so row-level security applies. The
config sets ``database.allow_table_owner = false`` so Axentra refuses to start if that ever breaks.

Deliberate test-only settings (all refused or meaningless in production, which this is not):
- ``environment = "development"``
- ``billing.provider = "fake"`` (never moves money, ``live_payments`` stays off)
- ``events.webhook_allow_http`` / ``webhook_allow_private_targets``: webhook endpoints of the seed
  point to 127.0.0.1 (an unreachable local port) so deliveries fail visibly without leaving the PC.
- SMTP without TLS/auth to the kit's local mail catcher on 127.0.0.1 (loopback only).
"""

from __future__ import annotations

import base64
import os
import secrets
from pathlib import Path

DB_NAME = "axentra"
OWNER_ROLE = "axentra_owner"
APP_ROLE = "axentra_app"
CONFIG_NAME = "axentra.toml"

#: Long-running processes the kit needs next to the web process, as axentra CLI arguments after
#: ``--config <cfg>``: the job worker (jobs, schedules, webhook deliveries, event fan-out) and the
#: notification dispatcher (sends queued emails to the SMTP catcher).
BACKGROUND_PROCESSES: list[tuple[str, list[str]]] = [
    ("worker", ["worker", "--concurrency", "2"]),
    ("notify", ["notify-dispatch", "--loop", "--interval", "2"]),
]


def config_path(state_dir: Path) -> Path:
    """Where :func:`prepare` writes the Axentra configuration."""
    return Path(state_dir).resolve() / CONFIG_NAME


def _write_secret(path: Path, value: str) -> None:
    """Write ``value`` to ``path`` with mode 0600 (created with that mode, never world-readable)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        path.parent.chmod(0o700)
    except OSError:  # pragma: no cover - e.g. Windows ACLs
        pass
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    fd = os.open(path, flags, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(value + "\n")
    try:
        path.chmod(0o600)
    except OSError:  # pragma: no cover
        pass


def _toml_str(value: str) -> str:
    """A TOML basic string (paths on Windows contain backslashes)."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _file_ref(path: Path) -> str:
    return "file:" + str(path.resolve())


def prepare(state_dir: Path, pg_port: int, http_port: int, smtp_port: int) -> Path:
    """Write the config and fresh secrets into ``state_dir``; return the config file path."""
    state_dir = Path(state_dir).resolve()
    state_dir.mkdir(parents=True, exist_ok=True)
    sec = state_dir / "secrets"
    storage = state_dir / "storage"
    storage.mkdir(parents=True, exist_ok=True)

    # Hex passwords are URL-safe, so they can go into connection URLs unchanged.
    owner_pw = secrets.token_hex(24)
    app_pw = secrets.token_hex(24)
    key = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode().rstrip("=")
    files = {
        "db_owner_password": owner_pw,
        "db_app_password": app_pw,
        "db_owner_url": f"postgresql://{OWNER_ROLE}:{owner_pw}@127.0.0.1:{pg_port}/{DB_NAME}",
        "db_app_url": f"postgresql://{APP_ROLE}:{app_pw}@127.0.0.1:{pg_port}/{DB_NAME}",
        "master_keys": f"k1:{key}",
        "billing_webhook_secret": "whsec_" + secrets.token_hex(24),
    }
    for name, value in files.items():
        _write_secret(sec / name, value)

    public_url = f"http://127.0.0.1:{http_port}"
    text = f"""# Axentra configuration of the local QA test kit (generated by qakit/runtime/qa_config.py).
# NOT a production configuration: test data only, everything listens on 127.0.0.1.
# Secrets are referenced as file: paths below the secrets folder (mode 0600), never inline.

environment = "development"
mode = "multi"
# All modules that exist (Axentra's default list).
modules = ["identity", "tenancy", "access", "data", "audit", "storage", "events", "usage",
           "billing", "notify", "search", "realtime"]

[database]
# Runtime role: no superuser, no BYPASSRLS, owns no tables -> row-level security applies.
url_ref = {_toml_str(_file_ref(sec / "db_app_url"))}
# Owner role: owns the schema and runs migrations and `axentra db grant-runtime-role`.
migration_url_ref = {_toml_str(_file_ref(sec / "db_owner_url"))}
allow_superuser = false
allow_table_owner = false
require_current_schema = true
pool_min = 1
pool_max = 10

[security]
public_url = {_toml_str(public_url)}
# Studio and the API share one origin (public_url is always allowed). localhost is listed too so the
# kit also works when a tester types http://localhost:<port>.
allowed_origins = [{_toml_str(f"http://localhost:{http_port}")}]
master_keys_ref = {_toml_str(_file_ref(sec / "master_keys"))}
password_login = true
# /v1/docs and /v1/openapi.json only for signed-in users (the Studio session cookie works, same origin).
api_docs = "authenticated"

[storage]
backend = "local"
local_path = {_toml_str(str(storage))}

[notify]
# Real SMTP delivery to the kit's local mail catcher (plain SMTP on loopback, no auth).
provider = "smtp"
sender = "Axentra QA (Test) <no-reply@axentra-qa.test>"
smtp_host = "127.0.0.1"
smtp_port = {int(smtp_port)}
smtp_starttls = false
smtp_timeout_seconds = 5.0
# Short retries so a stopped catcher shows up as failed messages quickly.
max_attempts = 3
backoff_base_seconds = 10.0
backoff_max_seconds = 60.0

[billing]
provider = "fake"
live_payments = false
# Lets the seed (and testers' tools) sign webhook events of the fake provider.
webhook_secret_ref = {_toml_str(_file_ref(sec / "billing_webhook_secret"))}

[events]
# Seeded webhook endpoints point to an unreachable port on 127.0.0.1 (deliveries fail visibly).
webhook_allow_http = true
webhook_allow_private_targets = true
webhook_timeout_seconds = 3.0
# Faster retries than production so the tester sees attempts within minutes.
webhook_max_attempts = 4
webhook_backoff_base_seconds = 30.0
webhook_backoff_max_seconds = 300.0

[observability]
log_level = "INFO"
log_format = "text"
otel_enabled = false
"""
    config = config_path(state_dir)
    config.write_text(text, encoding="utf-8")
    return config


if __name__ == "__main__":  # manual use: python qa_config.py <state_dir> <pg> <http> <smtp>
    import sys

    print(prepare(Path(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])))
